#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { isDeepStrictEqual } from "node:util";

const COVERAGE_SCOPES = [
  {
    name: "core",
    label: "Core/unit coverage",
    summaryPath: "coverage/core/coverage-summary.json",
    scope:
      "Compiled build-test core modules exercised by unit tests, excluding test files, mounted React views/components, motion/theme shells, and entrypoints.",
  },
  {
    name: "scripts",
    label: "Browser/release/CLI script coverage",
    summaryPath: "coverage/scripts/coverage-summary.json",
    scope:
      "Repository scripts exercised by unit tests with optional desktop/Tauri bootstrap helpers excluded from the supported browser/PWA and CLI release scope.",
  },
  {
    name: "combined",
    label: "Combined core plus script coverage",
    summaryPath: "coverage/combined/coverage-summary.json",
    scope: "Union of the core and scripts coverage scopes, using the same include/exclude rules.",
  },
];

const CANONICAL_CI_NODE_VERSION = "20.19.0";
const CANONICAL_NODE_VERSION = `v${CANONICAL_CI_NODE_VERSION}`;

const args = process.argv.slice(2);
const writePath = readFlagValue("--write");
const verifyPath = readFlagValue("--verify");
const assertCanonical = args.includes("--assert-canonical");

if (args.includes("--help")) {
  console.log("Usage: node scripts/coverage-evidence.mjs [--write path] [--verify path] [--assert-canonical]");
  process.exit(0);
}

const evidence = buildEvidence();

console.log(
  `coverage runtime: ${evidence.runtime.kind} (${evidence.runtime.node}, V8 ${evidence.runtime.v8}; canonical ${evidence.runtime.canonicalNode})`,
);

for (const scope of evidence.scopes) {
  const total = scope.total;
  console.log(
    `${scope.name}: ${total.lines.pct}% lines/statements, ${total.functions.pct}% functions, ${total.branches.pct}% branches (${scope.fileCount} files)`,
  );
}

if (writePath) {
  writeJson(writePath, evidence);
  console.log(`coverage evidence written to ${writePath}`);
}

if (verifyPath) {
  const actual = JSON.parse(fs.readFileSync(verifyPath, "utf8"));
  if (!isDeepStrictEqual(actual, evidence)) {
    console.error(`coverage evidence diverges from current c8 summaries: ${verifyPath}`);
    process.exit(1);
  }
  console.log(`coverage evidence verified against ${verifyPath}`);
}

if (assertCanonical) {
  assertCanonicalRuntime(evidence);
}

function readFlagValue(flag) {
  const index = args.indexOf(flag);
  if (index === -1) return "";
  const value = args[index + 1];
  if (!value || value.startsWith("--")) {
    console.error(`${flag} requires a path`);
    process.exit(1);
  }
  return value;
}

function buildEvidence() {
  const runtime = runtimeMetadata();
  return {
    version: 3,
    source: "c8 json-summary reports generated by npm run coverage",
    runtime,
    canonicalRuntime: runtime,
    scopes: COVERAGE_SCOPES.map((scope) => {
      const summary = readSummary(scope.summaryPath);
      const files = Object.keys(summary).filter((key) => key !== "total").sort();
      assertNoDuplicateSources(scope, files);
      return {
        name: scope.name,
        label: scope.label,
        summaryPath: scope.summaryPath,
        scope: scope.scope,
        fileCount: files.length,
        total: pickTotals(summary.total),
      };
    }),
  };
}

function runtimeMetadata() {
  const isCanonical = process.version === CANONICAL_NODE_VERSION;
  return {
    node: process.version,
    v8: process.versions.v8,
    canonicalNode: CANONICAL_NODE_VERSION,
    ciNode: CANONICAL_CI_NODE_VERSION,
    kind: isCanonical ? "canonical" : "noncanonical",
    isCanonical,
  };
}

function assertCanonicalRuntime(evidenceValue) {
  if (!evidenceValue.runtime?.isCanonical || evidenceValue.runtime.node !== CANONICAL_NODE_VERSION) {
    console.error(
      `coverage evidence is ${evidenceValue.runtime?.kind ?? "unknown"}; canonical release evidence requires Node ${CANONICAL_NODE_VERSION}`,
    );
    process.exit(1);
  }
}

function readSummary(summaryPath) {
  const absolutePath = path.resolve(summaryPath);
  if (!fs.existsSync(absolutePath)) {
    console.error(`missing coverage summary: ${summaryPath}`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(absolutePath, "utf8"));
}

function pickTotals(total) {
  return {
    lines: pickMetric(total.lines),
    statements: pickMetric(total.statements),
    functions: pickMetric(total.functions),
    branches: pickMetric(total.branches),
  };
}

function pickMetric(metric) {
  return {
    total: metric.total,
    covered: metric.covered,
    skipped: metric.skipped,
    pct: metric.pct,
  };
}

function assertNoDuplicateSources(scope, files) {
  const seen = new Map();
  for (const file of files) {
    const logical = logicalSourceKey(file);
    const previous = seen.get(logical);
    if (previous) {
      console.error(`${scope.name} coverage scope contains duplicate logical source: ${previous} and ${file}`);
      process.exit(1);
    }
    seen.set(logical, file);
  }
}

function logicalSourceKey(file) {
  return file
    .replace(/\\/g, "/")
    .replace(/^build-test\//u, "")
    .replace(/^src\//u, "");
}

function writeJson(outputPath, value) {
  fs.mkdirSync(path.dirname(path.resolve(outputPath)), { recursive: true });
  fs.writeFileSync(outputPath, `${JSON.stringify(value, null, 2)}\n`);
}
